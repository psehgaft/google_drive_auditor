export function setLocale(value){language=Object.hasOwn(catalogs,value)?value:"en";return language}
export function t(key,params={}){return (catalogs[language][key]??key).replace(/\{(\w+)\}/g,(m,k)=>Object.hasOwn(params,k)?String(params[k]):m)}
